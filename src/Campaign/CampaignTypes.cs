using System.Collections.Generic;
using System.Text;
using LiteNetLib.Utils;

namespace SeapowerMultiplayer.Campaign
{
    /// <summary>Which player a campaign asset (fleet, theatre, command post) answers to.</summary>
    public enum CampaignSeat : byte
    {
        /// <summary>Either player may command it.</summary>
        Shared = 0,
        Host   = 1,
        Guest  = 2,
        /// <summary>Nobody (e.g. AI-controlled allied forces in Career mode).</summary>
        Locked = 3,
        Guest2 = 4,   // slot 2
        Guest3 = 5,   // slot 3
    }

    /// <summary>Player slot &lt;-&gt; campaign seat. Slot 0 is the host.</summary>
    public static class Seats
    {
        public const int MaxPlayers = 4;

        public static CampaignSeat OfSlot(byte slot) => slot switch
        {
            0 => CampaignSeat.Host,
            1 => CampaignSeat.Guest,
            2 => CampaignSeat.Guest2,
            3 => CampaignSeat.Guest3,
            _ => CampaignSeat.Locked,
        };

        /// <summary>The player slot of a player seat, or null for Shared/Locked.</summary>
        public static byte? SlotOf(CampaignSeat seat) => seat switch
        {
            CampaignSeat.Host   => 0,
            CampaignSeat.Guest  => 1,
            CampaignSeat.Guest2 => 2,
            CampaignSeat.Guest3 => 3,
            _ => null,
        };

        public static bool IsPlayer(CampaignSeat seat) => SlotOf(seat) != null;

        public static CampaignSeat Local => OfSlot(SeapowerMultiplayer.PlayerRegistry.LocalSlot);

        /// <summary>"you", or the player's name, or "another player" if they left.</summary>
        public static string NameOf(CampaignSeat seat)
        {
            var slot = SlotOf(seat);
            if (slot == null) return seat == CampaignSeat.Locked ? "the AI" : "everyone";
            if (slot == SeapowerMultiplayer.PlayerRegistry.LocalSlot) return "you";
            string n = SeapowerMultiplayer.PlayerRegistry.DisplayName(slot.Value);
            return string.IsNullOrEmpty(n) ? "another player" : n;
        }
    }

    /// <summary>Battle transition stages the host announces to the guest.</summary>
    public enum BattleStage : byte
    {
        None      = 0,
        Starting  = 1,  // the campaign chose a battle; the host is loading it
        Sending   = 2,  // the host's battle is live and on its way to the guest
        Returning = 3,  // battle over; the host is going back to the campaign map
    }

    /// <summary>What the host's campaign is doing right now.</summary>
    public enum CampaignPhase : byte
    {
        None     = 0,  // no campaign loaded
        Map      = 1,  // strategic layer, players giving orders
        Battle   = 2,  // a tactical battle generated by the campaign is live
        Resolving = 3, // battle over, campaign absorbing the result
        Ended    = 4,  // war over
    }

    /// <summary>
    /// One player action on the campaign map, in adapter-neutral form.
    ///
    /// <para><b>Id</b> names the action ("fleet.move", "op.launch", ...). The
    /// vocabulary belongs to the adapter - CampaignSync never interprets it beyond
    /// routing, which keeps the core independent of any one campaign mod.</para>
    ///
    /// <para><b>AssetKey</b> is the thing the action commands (a fleet id, a
    /// theatre id). Ownership is checked against it. Empty = a campaign-wide action
    /// (end turn, change time speed), which is checked against the "global" rules.</para>
    ///
    /// <para><b>Args</b> are ordered string pairs, the same shape the game's own ini
    /// layer uses, so adapters can serialize campaign objects with whatever
    /// text form the mod already writes to its save files.</para>
    /// </summary>
    public sealed class CampaignCommand
    {
        public string Id       = "";
        public string AssetKey = "";
        public readonly List<(string key, string value)> Args = new();

        public CampaignCommand Arg(string key, string value)
        {
            Args.Add((key, value ?? ""));
            return this;
        }

        public string? Get(string key)
        {
            for (int i = 0; i < Args.Count; i++)
                if (Args[i].key == key) return Args[i].value;
            return null;
        }

        public void Serialize(NetDataWriter w)
        {
            w.Put(Id ?? "");
            w.Put(AssetKey ?? "");
            w.Put((ushort)Args.Count);
            for (int i = 0; i < Args.Count; i++)
            {
                w.Put(Args[i].key);
                w.Put(Args[i].value);
            }
        }

        public static CampaignCommand Deserialize(NetDataReader r)
        {
            var c = new CampaignCommand { Id = r.GetString(), AssetKey = r.GetString() };
            int n = r.GetUShort();
            for (int i = 0; i < n; i++)
                c.Args.Add((r.GetString(), r.GetString()));
            return c;
        }

        public override string ToString()
        {
            var sb = new StringBuilder(Id);
            if (!string.IsNullOrEmpty(AssetKey)) sb.Append('[').Append(AssetKey).Append(']');
            for (int i = 0; i < Args.Count; i++)
                sb.Append(' ').Append(Args[i].key).Append('=').Append(Args[i].value);
            return sb.ToString();
        }
    }
}
